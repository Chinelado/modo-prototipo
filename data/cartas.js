// índice palavra → arquivos, só do idioma ativo; o artigo e o que vem depois de vírgula ou parêntese não contam
const CARD_PIC_IDX = (() => {
  const col = { de: 1, en: 2, es: 3 }[typeof LANG !== 'undefined' ? LANG : 'de'] || 1, idx = {};
  Object.entries(CARD_PICS).forEach(([file, row]) => (row[col] || '').split('|').filter(Boolean).forEach((w) => (idx[w] = idx[w] || []).push(file)));
  return idx;
})();
const cardWord = (s) => String(s || '').toLowerCase().split(/[,(;/]/)[0].replace(/^(der|die|das|the|an|a|el|la|los|las|lo|un|una|unos|unas)\s+/, '').replace(/[.!?¡¿]/g, '').trim();
// devolve o nome do arquivo da imagem da carta, ou '' quando a palavra não tem imagem
function cardPicFile(v) {
  if (!v || !v.de || !v.pt) return '';
  const pt = String(v.pt).toLowerCase(), hits = CARD_PIC_IDX[cardWord(v.de)] || [];
  return hits.find((f) => CARD_PICS[f][0].split('|').some((p) => pt.includes(p))) || '';
}
